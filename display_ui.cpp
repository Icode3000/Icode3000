// Draws `text` at (TEXT_X, y) using `font`. If it's wider than maxW it
// scrolls horizontally instead of getting clipped, wrapping around with a
// gap so it reads as a continuous loop. `offset` is advanced by the display
// task on a fixed timer, independent of animation rendering.
static void renderScrollLine(int y, const String &text, int &offset, const uint8_t *font, int maxW) {
  u8g2.setFont(font);
  int w = u8g2.getStrWidth(text.c_str());

  if (w <= maxW) {
    u8g2.drawStr(TEXT_X, y, text.c_str());
    offset = 0;
    return;
  }

  const int gap = 16;
  int total = w + gap;
  int drawX = TEXT_X - offset;

  u8g2.setClipWindow(TEXT_X, y - (u8g2.getAscent() - u8g2.getDescent()), 128, y + 2);
  u8g2.drawStr(drawX, y, text.c_str());
  u8g2.drawStr(drawX + total, y, text.c_str());
  u8g2.setMaxClipWindow();
}

// ---- Playback control icons (prev / play-pause / next) ----
static void drawTriangle(int cx, int cy, int r, bool pointRight) {
  if (pointRight) {
    u8g2.drawTriangle(cx - r, cy - r, cx - r, cy + r, cx + r, cy);
  } else {
    u8g2.drawTriangle(cx + r, cy - r, cx + r, cy + r, cx - r, cy);
  }
}

static void drawPauseBars(int cx, int cy, int r) {
  u8g2.drawBox(cx - r, cy - r, 4, r * 2);
  u8g2.drawBox(cx + r - 4, cy - r, 4, r * 2);
}

static void drawControlsRow() {
  const int r = 6;
  const int y = 55;
  int cx1 = TEXT_X + (128 - TEXT_X) / 6;
  int cx2 = TEXT_X + (128 - TEXT_X) / 2;
  int cx3 = TEXT_X + (128 - TEXT_X) * 5 / 6;

  drawTriangle(cx1, y, r, false);
  if (isPlaying) drawPauseBars(cx2, y, r);
  else           drawTriangle(cx2, y, r, true);
  drawTriangle(cx3, y, r, true);
}

// ---- Status bar (wifi bars + battery %) ----
static void drawWifiIcon(int x, int yBase, int bars) {
  for (int i = 0; i < 4; i++) {
    int barH = 2 + i * 2;
    int bx = x + i * 3;
    if (i < bars) u8g2.drawBox(bx, yBase - barH, 2, barH);
    else          u8g2.drawFrame(bx, yBase - barH, 2, barH);
  }
}

static void drawBatteryIcon(int x, int y, int percent) {
  const int w = 14, h = 7, nub = 2;
  u8g2.drawFrame(x, y, w, h);
  u8g2.drawBox(x + w, y + 2, nub, h - 4);
  int fillW = (w - 2) * percent / 100;
  if (fillW > 0) u8g2.drawBox(x + 1, y + 1, fillW, h - 2);
}

static void drawStatusBar() {
  u8g2.setFont(u8g2_font_5x8_tf);
  char buf[6];
  snprintf(buf, sizeof(buf), "%d%%", batteryPercent);
  int textW = u8g2.getStrWidth(buf);

  const int batteryW = 14, wifiW = 10, gap = 3;
  int batteryX = 128 - batteryW - 2;
  int textX = batteryX - gap - textW;
  int wifiX = textX - gap - wifiW;

  drawWifiIcon(wifiX, 9, wifiBars);
  u8g2.drawStr(textX, 8, buf);
  drawBatteryIcon(batteryX, 1, batteryPercent);
}

// Picks the smallest QR version (1-6) whose byte-mode/ECC_LOW capacity
// fits the payload, so the code renders at the largest possible integer
// pixel scale within the 64x64 area instead of being stuck oversized-version/undersized-render.
static int pickQrVersion(size_t len) {
  static const int capacity[] = {17, 32, 53, 78, 106, 134};  // v1..v6, byte mode, ECC_LOW
  for (int v = 0; v < 6; v++) {
    if ((int)len <= capacity[v]) return v + 1;
  }
  return 6;
}

void displayShowWifiSetup(const String &qrPayload, const String &apSsid, const String &portalIp) {
  if (displayMutex) xSemaphoreTake(displayMutex, portMAX_DELAY);

  int version = pickQrVersion(qrPayload.length());
  QRCode qrcode;
  uint8_t qrcodeData[qrcode_getBufferSize(6)];  // sized for the largest version we ever pick
  qrcode_initText(&qrcode, qrcodeData, version, ECC_LOW, qrPayload.c_str());

  int n = qrcode.size;
  int scale = 64 / n;             // largest integer scale that still fits the 64x64 area
  if (scale < 1) scale = 1;
  int qrPx = n * scale;
  int qx = (64 - qrPx) / 2;   // centered in the left 64px half
  int qy = (64 - qrPx) / 2;

  u8g2.clearBuffer();
  for (int y = 0; y < n; y++) {
    for (int x = 0; x < n; x++) {
      if (qrcode_getModule(&qrcode, x, y)) {
        u8g2.drawBox(qx + x * scale, qy + y * scale, scale, scale);
      }
    }
  }

  u8g2.setFont(u8g2_font_6x10_tf);
  u8g2.drawStr(66, 10, "Scan to");
  u8g2.drawStr(66, 22, "set up WiFi");
  u8g2.setFont(u8g2_font_5x8_tf);
  u8g2.drawStr(66, 36, "or join AP:");
  u8g2.drawStr(66, 46, apSsid.c_str());
  u8g2.drawStr(66, 58, portalIp.c_str());

  u8g2.sendBuffer();

  if (displayMutex) xSemaphoreGive(displayMutex);
}

