// ---- PackBits-style RLE decoder (unchanged) ----
// header < 128:  (header + 1) literal bytes follow, copy verbatim
// header >= 128: (257 - header) repeats of the single byte that follows
static void packbitsDecode(const uint8_t *src, uint16_t srcLen, uint8_t *dst, uint16_t dstLen) {
  uint16_t si = 0, di = 0;
  while (si < srcLen && di < dstLen) {
    uint8_t header = pgm_read_byte(src + si++);
    if (header < 128) {
      uint8_t count = header + 1;
      for (uint8_t k = 0; k < count && di < dstLen && si < srcLen; k++) {
        dst[di++] = pgm_read_byte(src + si++);
      }
    } else {
      uint16_t count = 257 - header;
      uint8_t val = pgm_read_byte(src + si++);
      for (uint16_t k = 0; k < count && di < dstLen; k++) {
        dst[di++] = val;
      }
    }
  }
}

static void loadFrame(int idx) {
  uint16_t offset = pgm_read_word(&frame_offsets[idx]);
  uint16_t length = pgm_read_word(&frame_lengths[idx]);
  packbitsDecode(frame_data + offset, length, frameBuf, sizeof(frameBuf));

  // Your original frame data was authored for Adafruit_GFX's drawBitmap(),
  // which packs bits MSB-first per byte. U8g2's drawXBM() expects the XBM
  // convention (LSB-first per byte) instead — same bytes, opposite bit
  // order, so without this correction the image comes out scrambled
  // (effectively invisible). Reverse each byte to fix it.
  for (size_t i = 0; i < sizeof(frameBuf); i++) {
    uint8_t b = frameBuf[i];
    b = (b & 0xF0) >> 4 | (b & 0x0F) << 4;
    b = (b & 0xCC) >> 2 | (b & 0x33) << 2;
    b = (b & 0xAA) >> 1 | (b & 0x55) << 1;
    frameBuf[i] = b;
  }
}

void displayBegin() {
  Wire.begin(OLED_SDA, OLED_SCL);
  u8g2.begin();
  u8g2.setBusClock(400000);

  // The OLED renderer runs in its own FreeRTOS task. This is important because
  // Spotify HTTPS polling can block the Arduino loop for hundreds of ms or more.
  // Keeping rendering independent means animation + text scrolling stay smooth.
  displayMutex = xSemaphoreCreateMutex();
  if (displayMutex) {
    xTaskCreatePinnedToCore(
      displayTask,
      "OLED_Render",
      8192,
      nullptr,
      1,
      &displayTaskHandle,
      0
    );
  }
}

