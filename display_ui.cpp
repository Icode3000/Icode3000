static void render() {
  u8g2.clearBuffer();

  if (songListMode) {
    renderSongList();
    u8g2.sendBuffer();
    return;
  }

  if (deviceListMode) {
    renderDeviceList();
    u8g2.sendBuffer();
    return;
  }

  if (idleMode) {
    renderIdle();
    u8g2.sendBuffer();
    return;
  }

  if (trackName.length() > 0) {
    loadFrame(isPlaying ? animFrame : 0);
    u8g2.drawXBM(ANIM_X, 0, FRAME_WIDTH, FRAME_HEIGHT, frameBuf);
  }

  drawStatusBar();
  renderScrollLine(30, trackName, nameOffset, u8g2_font_logisoso18_tr, TEXT_W);
  renderScrollLine(44, trackArtist, artistOffset, u8g2_font_7x13_tf, TEXT_W);
  drawControlsRow();
  u8g2.sendBuffer();
}

void displayUpdate(const String &name, const String &artist, bool playing) {
  if (displayMutex) xSemaphoreTake(displayMutex, portMAX_DELAY);

  if (name != trackName) nameOffset = 0;
  if (artist != trackArtist) artistOffset = 0;
  if (playing != isPlaying) {
    animFrame = 0;
    lastAnimMs = millis();
  }
  if (playing) idleMode = false;  // resuming playback always cancels the idle screen

  trackName = name;
  trackArtist = artist;
  isPlaying = playing;
  forceRedraw = true;

  if (displayMutex) xSemaphoreGive(displayMutex);
}

void displayShowMessage(const String &line1, const String &line2) {
  if (displayMutex) xSemaphoreTake(displayMutex, portMAX_DELAY);
  u8g2.clearBuffer();
  u8g2.setFont(u8g2_font_6x10_tf);
  u8g2.drawStr(4, 30, line1.c_str());
  if (line2.length()) u8g2.drawStr(4, 45, line2.c_str());
  u8g2.sendBuffer();
  if (displayMutex) xSemaphoreGive(displayMutex);
}

// Dedicated OLED renderer. It wakes frequently but only sends a full frame
// when animation, scrolling, or a state/data change actually requires it.
static void displayTask(void *parameter) {
  (void)parameter;

  for (;;) {
    unsigned long now = millis();
    bool needsRedraw = false;

    if (displayMutex) xSemaphoreTake(displayMutex, portMAX_DELAY);

    if (isPlaying && now - lastAnimMs >= FRAME_DELAY_MS) {
      // Preserve the original 100 ms animation timing while catching up cleanly.
      lastAnimMs = now;
      animFrame = (animFrame + 1) % FRAME_COUNT;
      needsRedraw = true;
    }

    if (now - lastScrollMs >= 120) {
      lastScrollMs = now;

      u8g2.setFont(u8g2_font_logisoso18_tr);
      bool nameScrolls = u8g2.getStrWidth(trackName.c_str()) > TEXT_W;
      u8g2.setFont(u8g2_font_7x13_tf);
      bool artistScrolls = u8g2.getStrWidth(trackArtist.c_str()) > TEXT_W;

      if (nameScrolls) {
        int w = u8g2.getStrWidth(trackName.c_str());
        int total = w + 16;
        nameOffset = (nameOffset + 1) % total;
      } else {
        nameOffset = 0;
      }

      if (artistScrolls) {
        int w = u8g2.getStrWidth(trackArtist.c_str());
        int total = w + 16;
        artistOffset = (artistOffset + 1) % total;
      } else {
        artistOffset = 0;
      }

      if (nameScrolls || artistScrolls) needsRedraw = true;
    }

    if (forceRedraw) {
      forceRedraw = false;
      needsRedraw = true;
    }

    if (needsRedraw) render();

    if (displayMutex) xSemaphoreGive(displayMutex);

    // 5 ms scheduler granularity keeps timing smooth without busy-spinning.
    vTaskDelay(pdMS_TO_TICKS(5));
  }
}

