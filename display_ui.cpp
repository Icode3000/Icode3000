static void loadIdleImage() {
  for (size_t i = 0; i < sizeof(frameBuf); i++) {
    uint8_t b = pgm_read_byte(&idle_frame_data[i]);
    b = (b & 0xF0) >> 4 | (b & 0x0F) << 4;
    b = (b & 0xCC) >> 2 | (b & 0x33) << 2;
    b = (b & 0xAA) >> 1 | (b & 0x55) << 1;
    frameBuf[i] = b;
  }
}

// Spotify logo + starfield, shown after IDLE_TIMEOUT_MS of no playback.
// Spotify Connect device picker, shown on a play/pause long-press.
static void renderDeviceList() {
  const int lineH = 12;
  const int visibleRows = 4;
  int totalRows = deviceListRealCount + 1;  // +1 for "Back"

  int start = deviceListSelIdx - visibleRows / 2;
  if (start < 0) start = 0;
  if (start > totalRows - visibleRows) start = max(0, totalRows - visibleRows);

  u8g2.setFont(u8g2_font_6x10_tf);
  u8g2.drawStr(2, 10, "Play on device:");
  u8g2.drawHLine(0, 12, 128);

  for (int row = 0; row < visibleRows; row++) {
    int idx = start + row;
    if (idx >= totalRows) break;

    int y = 26 + row * lineH;
    bool selected = (idx == deviceListSelIdx);
    String label = deviceListNames[idx];
    if (idx == deviceListActiveIdx) label += " *";

    if (selected) {
      u8g2.drawBox(0, y - 9, 128, lineH);
      u8g2.setDrawColor(0);
      u8g2.drawStr(4, y, label.c_str());
      u8g2.setDrawColor(1);
    } else {
      u8g2.drawStr(4, y, label.c_str());
    }
  }
}

void displayShowDeviceList(const String *names, int count, int activeIndex) {
  if (displayMutex) xSemaphoreTake(displayMutex, portMAX_DELAY);

  int n = min(count, MAX_DEVICE_LIST);
  for (int i = 0; i < n; i++) deviceListNames[i] = names[i];
  deviceListNames[n] = "< Back";
  deviceListRealCount = n;
  deviceListActiveIdx = activeIndex;
  deviceListSelIdx = 0;
  deviceListMode = true;
  forceRedraw = true;

  if (displayMutex) xSemaphoreGive(displayMutex);
}

void displayDeviceListMove(int delta) {
  if (displayMutex) xSemaphoreTake(displayMutex, portMAX_DELAY);

  int totalRows = deviceListRealCount + 1;
  if (totalRows > 0) {
    deviceListSelIdx = ((deviceListSelIdx + delta) % totalRows + totalRows) % totalRows;
  }
  forceRedraw = true;

  if (displayMutex) xSemaphoreGive(displayMutex);
}

